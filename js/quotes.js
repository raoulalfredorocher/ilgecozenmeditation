/**
 * Restituisce la frase del giorno in base al giorno dell'anno (1–365).
 * Il giorno 366 degli anni bisestili usa l'ultima frase.
 */
export function getDailyQuote() {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay); // 1–366
  const index = Math.min(dayOfYear, QUOTES.length) - 1;
  return QUOTES[index];
}
